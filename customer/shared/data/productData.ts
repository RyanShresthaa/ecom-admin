// ── Types ──

export interface Artisan {
  name: string;
  bio: string[];
  image: string;
  stats: {
    yearsOfCraft: number;
    itemsCreated: number;
    apprentices: number;
  };
}

export interface Product {
  id: string;
  name: string;
  slug: string;
  category: string;
  location: string;
  /** Formatted price in the active shop display currency. */
  price: string;
  /** Catalog/base amount (usually NPR) before FX conversion. */
  basePrice?: number;
  image: string;
  // Detail-page fields
  subtitle: string;
  description: string;
  originalPrice: string;
  discount: string;
  medium: string;
  dimensions: string;
  age: string;
  school: string;
  stock: number;
  galleryImages: string[];
  tags: string[];
  artisan: Artisan;
}

export interface CategoryGroup {
  name: string;
  description: string;
  products: Product[];
}

// ── Helpers ──

export function generateSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

export function getAllProducts(): Product[] {
  return productCategories.reduce<Product[]>(
    (acc, group) => [...acc, ...group.products],
    []
  );
}

export function getProductBySlug(slug: string): Product | undefined {
  return getAllProducts().find((p) => p.slug === slug);
}

export function getCategoryForProduct(product: Product): CategoryGroup | undefined {
  return productCategories.find((group) =>
    group.products.some((p) => p.id === product.id)
  );
}

